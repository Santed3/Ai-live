const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  chat: (text, voice) => ipcRenderer.invoke('chat', { text, voice }),
  chips: () => ipcRenderer.invoke('chips'),
  reply: () => ipcRenderer.invoke('reply'),
  transform: (instruction, text) => ipcRenderer.invoke('transform', { instruction, text }),
  insert: (text, send) => ipcRenderer.invoke('insert', { text, send }),
  copy: (text) => ipcRenderer.invoke('copy', text),
  newChat: () => ipcRenderer.invoke('new-chat'),
  setMode: (m) => ipcRenderer.invoke('set-mode', m),
  quick: () => ipcRenderer.invoke('quick'),
  barMove: (y) => ipcRenderer.send('bar-move', { y }),
  onView: (cb) => ipcRenderer.on('view', (_e, v) => cb(v)),
  hide: () => ipcRenderer.invoke('set-mode', 'hide'),
  quit: () => ipcRenderer.invoke('quit'),
  stt: (buf) => ipcRenderer.invoke('stt', buf),
  getSettings: () => ipcRenderer.invoke('settings-get'),
  setSettings: (s) => ipcRenderer.invoke('settings-set', s),
  confirmReply: (id, ok) => ipcRenderer.send('confirm-reply', { id, ok }),
  openLink: (u) => ipcRenderer.invoke('open-link', u),
  onDelta: (cb) => ipcRenderer.on('delta', (_e, t) => cb(t)),
  onDeltaReset: (cb) => ipcRenderer.on('delta-reset', () => cb()),
  onAsk: (cb) => ipcRenderer.on('ask', (_e, t) => cb(t)),
  autostartGet: () => ipcRenderer.invoke('autostart-get'),
  autostartSet: (on) => ipcRenderer.invoke('autostart-set', on),
  archiveList: (q) => ipcRenderer.invoke('archive-list', q),
  archiveOpen: (id) => ipcRenderer.invoke('archive-open', id),
  archiveDelete: (id) => ipcRenderer.invoke('archive-delete', id),
  archiveClear: () => ipcRenderer.invoke('archive-clear'),
  commandsGet: () => ipcRenderer.invoke('commands-get'),
  commandsSave: (c) => ipcRenderer.invoke('commands-save', c),
  commandsDelete: (id) => ipcRenderer.invoke('commands-delete', id),
  styleAdd: (t) => ipcRenderer.invoke('style-add', t),
  memoryGet: () => ipcRenderer.invoke('memory-get'),
  memorySet: (l) => ipcRenderer.invoke('memory-set', l),
  memoryAutoGet: () => ipcRenderer.invoke('memory-auto-get'),
  memoryAutoSet: (on) => ipcRenderer.invoke('memory-auto-set', on),
  updateState: () => ipcRenderer.invoke('update-state'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, s) => cb(s)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, t) => cb(t)),
  onConfirm: (cb) => ipcRenderer.on('confirm-request', (_e, m) => cb(m)),
  onShown: (cb) => ipcRenderer.on('panel-shown', () => cb()),
  // dot
  dotClick: () => ipcRenderer.send('dot-click'),
  dotDouble: () => ipcRenderer.send('dot-dbl'),
  dotPanel: () => ipcRenderer.send('dot-panel'),
  dotMove: (x, y) => ipcRenderer.send('dot-move', { x, y }),
  dotSave: () => ipcRenderer.send('dot-save'),
  // answer bubble
  onAnswer: (cb) => ipcRenderer.on('answer-text', (_e, t) => cb(t)),
  answerClick: () => ipcRenderer.send('answer-click'),
});
